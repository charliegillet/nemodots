#!/usr/bin/env python3
"""Static build-kit checks, not a Claude agent/runtime or NemoDots product validator."""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re
import sys

KIT = Path(__file__).resolve().parent
APP = KIT.parent / "NemoDots"
EXPECTED_MODELS = {"claude-opus-5", "claude-sonnet-5-5"}
TOOLS = {"Read", "Glob", "Grep", "Bash", "Write", "Edit"}


def main() -> None:
    agents = sorted((KIT / "claude/agents").glob("*.md"))
    assert len(agents) == 11, f"Expected 11 roles, got {len(agents)}"
    models: set[str] = set()
    names: set[str] = set()
    for path in agents:
        text = path.read_text()
        # Validate only the strict simple mapping subset generated by this kit.
        # This is deliberately not represented as an official Claude schema parser.
        assert text.startswith("---\n"), path
        header, body = text[4:].split("\n---\n", 1)
        fields = dict(line.split(": ", 1) for line in header.splitlines())
        assert set(fields) == {"name", "description", "model", "tools"}, path
        assert fields["name"] == path.stem and fields["name"] not in names, path
        assert fields["model"] in EXPECTED_MODELS, path
        assert set(fields["tools"].split(", ")) <= TOOLS, path
        assert "BUILD_PROMPT.md" in body and "TEST_PROMPT.md" in body, path
        models.add(fields["model"])
        names.add(fields["name"])
    assert models == EXPECTED_MODELS

    for name in ("BUILD_PROMPT.md", "TEST_PROMPT.md"):
        text = (KIT / name).read_text()
        assert text.count("```") % 2 == 0, f"Unbalanced fenced code: {name}"
        opened = re.findall(r"^<([a-z_0-9]+)>$", text, re.M)
        closed = re.findall(r"^</([a-z_0-9]+)>$", text, re.M)
        assert opened == closed, f"Unbalanced prompt tags: {name}"
        assert "claude-opus-5" in text and "claude-sonnet-5-5" in text
        assert "BLOCKED" in text and "NOT_RUN" in text

    settings = json.loads((KIT / "claude/settings.json").read_text())
    assert settings == {
        "env": {"CLAUDE_CODE_EXPERIMENTAL_AGENT_TEAMS": "1"},
        "teammateMode": "in-process",
    }
    launcher = (KIT / "launch-claude.sh").read_text()
    assert "exec claude --model claude-opus-5 --effort high" in launcher
    assert "--dangerously-skip-permissions" not in launcher
    assert "exec claude -p" not in launcher

    manifest = json.loads((KIT / "SOURCE_MANIFEST.json").read_text())
    assert manifest["application_implemented_by_preparation"] is False
    assert manifest["product_inference"]["live_verified_by_preparation"] is False
    for relative, expected in manifest["installed_assets"].items():
        path = APP / relative
        assert path.is_file(), f"Missing installed asset: {relative}"
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        assert actual == expected, f"Installed asset changed: {relative}"

    print(f"PASS: {len(agents)} role definitions, exact model split, prompt structure, launcher and installed asset hashes.")
    print("Static checks only. Claude role loading, native team creation, model access and application tests remain NOT_RUN.")


if __name__ == "__main__":
    try:
        main()
    except (AssertionError, OSError, ValueError) as error:
        print(f"FAIL: {error}", file=sys.stderr)
        sys.exit(1)
