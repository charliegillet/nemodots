#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from package-lock.json.
//
//   node scripts/nemodots/notices.mjs            write THIRD_PARTY_NOTICES.md
//   node scripts/nemodots/notices.mjs --check    exit 1 when the file is not what
//                                                the current lockfile produces
//
// Scope: every lockfile entry that is not marked `dev` (production dependencies,
// including optional and peer packages the lockfile installs). The license of
// each entry is the `license` field recorded in the lockfile. Entries without
// one are listed separately with an explicit note; nothing is guessed.
//
// The output is deterministic (no timestamps, sorted) and carries the sha256 of
// the lockfile it was generated from, so `--check` fails whenever the lockfile
// changes without a regeneration. docs/nemodots/audit/license-scan-prod.txt (the
// scan of installed packages made before pg and redis were added) seeds the
// cross-check printed to stderr on generation; it never changes the output.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const APP_ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const LOCKFILE = path.join(APP_ROOT, 'package-lock.json');
const OUTPUT = path.join(APP_ROOT, 'THIRD_PARTY_NOTICES.md');
const SEED_SCAN = path.join(
  APP_ROOT,
  'docs',
  'nemodots',
  'audit',
  'license-scan-prod.txt',
);

// Packages whose lockfile entry has no license field. Keyed by package name.
// A note here is a statement about evidence, not a license determination.
const UNLICENSED_NOTES = {
  khroma:
    'The lockfile and package.json carry no license field. The upstream project states the MIT License and the published package ships a license file with MIT text, but this was not verified against the upstream repository. Treated as MIT, unverified.',
};

function fail(message) {
  console.error(`notices: ${message}`);
  process.exit(2);
}

function packageName(lockKey) {
  const marker = 'node_modules/';
  const at = lockKey.lastIndexOf(marker);
  return at === -1 ? lockKey : lockKey.slice(at + marker.length);
}

function normalizeLicense(value) {
  if (value === undefined || value === null) return null;
  if (typeof value === 'string') return value.trim() || null;
  if (Array.isArray(value)) {
    const parts = value.map(normalizeLicense).filter(Boolean);
    return parts.length ? `(${parts.join(' OR ')})` : null;
  }
  if (typeof value === 'object' && typeof value.type === 'string')
    return value.type.trim() || null;
  return null;
}

export function collectPackages(lock) {
  const rows = [];
  for (const [key, entry] of Object.entries(lock.packages ?? {})) {
    if (key === '' || entry.dev === true || entry.link === true) continue;
    rows.push({
      name: entry.name ?? packageName(key),
      version: entry.version ?? 'unknown',
      license: normalizeLicense(entry.license),
      optional: entry.optional === true,
    });
  }
  rows.sort(
    (a, b) =>
      a.name.localeCompare(b.name, 'en') ||
      a.version.localeCompare(b.version, 'en'),
  );
  // The same name@version can be installed at several paths; list it once.
  return rows.filter(
    (row, i) =>
      i === 0 ||
      row.name !== rows[i - 1].name ||
      row.version !== rows[i - 1].version,
  );
}

export function renderNotices(lockText) {
  const lock = JSON.parse(lockText);
  const digest = createHash('sha256').update(lockText).digest('hex');
  const rows = collectPackages(lock);
  const byLicense = new Map();
  const unlicensed = [];
  for (const row of rows) {
    if (row.license === null) {
      unlicensed.push(row);
      continue;
    }
    if (!byLicense.has(row.license)) byLicense.set(row.license, []);
    byLicense.get(row.license).push(row);
  }
  const licenses = [...byLicense.keys()].sort(
    (a, b) =>
      byLicense.get(b).length - byLicense.get(a).length ||
      a.localeCompare(b, 'en'),
  );

  const out = [];
  out.push('# Third-party notices');
  out.push('');
  out.push(
    '<!-- Generated by scripts/nemodots/notices.mjs from package-lock.json. Do not edit by hand; run `node scripts/nemodots/notices.mjs` to regenerate. -->',
  );
  out.push('');
  out.push('## Upstream attribution');
  out.push('');
  out.push(
    'NemoDots is built on [OpenDots](https://github.com/CopilotKit/OpenDots) by CopilotKit, released under the MIT License. The application in this repository started from OpenDots commit `ab39f2508f3fd23a949837622456f3d61a108e9a`. The upstream copyright notice and license text are kept unchanged in [LICENSE](LICENSE).',
  );
  out.push('');
  out.push('## Production dependencies');
  out.push('');
  out.push(
    `Source: \`package-lock.json\` (sha256 \`${digest}\`). Scope: every lockfile entry not marked \`dev\`, which includes optional platform packages. Each distinct name and version is listed once; the license shown is the one the lockfile records. The full license text of each package is distributed with that package in \`node_modules/\`.`,
  );
  out.push('');
  out.push(
    `${rows.length} distinct production packages, ${licenses.length + (unlicensed.length ? 1 : 0)} license groups.`,
  );
  out.push('');
  out.push('| License | Packages |');
  out.push('| ------- | -------- |');
  for (const license of licenses)
    out.push(`| ${license} | ${byLicense.get(license).length} |`);
  if (unlicensed.length)
    out.push(`| no license field | ${unlicensed.length} |`);
  out.push('');
  if (unlicensed.length) {
    out.push('## Packages without a license field');
    out.push('');
    for (const row of unlicensed) {
      out.push(`- \`${row.name}@${row.version}\`: ${
        UNLICENSED_NOTES[row.name] ??
        'The lockfile records no license for this package. Not determined.'
      }`);
    }
    out.push('');
  }
  out.push('## Packages by license');
  out.push('');
  for (const license of licenses) {
    const group = byLicense.get(license);
    out.push(`### ${license} (${group.length})`);
    out.push('');
    out.push(group.map((row) => `\`${row.name}@${row.version}\``).join(', '));
    out.push('');
  }
  return out.join('\n');
}

function seedCrossCheck(rows) {
  if (!fs.existsSync(SEED_SCAN)) return;
  const seed = fs.readFileSync(SEED_SCAN, 'utf8');
  const total = /prod \(non-dev\) packages in lockfile: (\d+)/.exec(seed);
  const flagged = [...seed.matchAll(/^node_modules\/(\S+) => UNKNOWN$/gm)].map(
    (m) => m[1],
  );
  const missing = rows.filter((r) => r.license === null).map((r) => r.name);
  const lines = [];
  if (total)
    lines.push(
      `seed scan: ${total[1]} packages before pg and redis were added; lockfile now has ${rows.length} distinct name@version entries (path duplicates collapsed)`,
    );
  const sameFlags =
    flagged.length === missing.length &&
    flagged.every((name) => missing.includes(name));
  lines.push(
    sameFlags
      ? `seed scan flagged ${flagged.join(', ') || 'nothing'}: matches the lockfile`
      : `seed scan flagged [${flagged.join(', ')}] but the lockfile has no license for [${missing.join(', ')}]`,
  );
  for (const line of lines) console.error(`notices: ${line}`);
}

function main(argv) {
  const check = argv.includes('--check');
  const unknown = argv.filter((a) => a !== '--check' && a !== '--write');
  if (unknown.length) fail(`unknown argument ${unknown[0]}`);
  if (!fs.existsSync(LOCKFILE)) fail('package-lock.json not found');
  const lockText = fs.readFileSync(LOCKFILE, 'utf8');
  const expected = `${renderNotices(lockText)}`;
  if (check) {
    const actual = fs.existsSync(OUTPUT)
      ? fs.readFileSync(OUTPUT, 'utf8')
      : null;
    if (actual === expected) {
      console.log('THIRD_PARTY_NOTICES.md is current');
      return;
    }
    console.error(
      actual === null
        ? 'notices: THIRD_PARTY_NOTICES.md is missing; run node scripts/nemodots/notices.mjs'
        : 'notices: THIRD_PARTY_NOTICES.md is stale for the current package-lock.json; run node scripts/nemodots/notices.mjs',
    );
    process.exit(1);
  }
  fs.writeFileSync(OUTPUT, expected);
  seedCrossCheck(collectPackages(JSON.parse(lockText)));
  console.log(`wrote ${path.relative(APP_ROOT, OUTPUT)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  main(process.argv.slice(2));
