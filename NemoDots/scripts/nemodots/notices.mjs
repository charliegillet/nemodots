#!/usr/bin/env node
// Generates THIRD_PARTY_NOTICES.md from the repository's own files:
//   - LICENSE (the upstream OpenDots MIT notice, quoted verbatim),
//   - deployment/computers/LICENSE.openbot (the OpenBot MIT notice),
//   - package-lock.json (every installed package that is not dev-only: name,
//     exact version, declared SPDX license),
//   - node_modules/<package>/ licence files for a package that declares none.
// Nothing is invented: a package with no declared licence is listed as such.
//
//   node scripts/nemodots/notices.mjs            write THIRD_PARTY_NOTICES.md
//   node scripts/nemodots/notices.mjs --check    exit 1 if the file is stale or
//                                                a production package is under
//                                                a copyleft licence
//   node scripts/nemodots/notices.mjs --stdout   print instead of writing
//
// The output has no timestamp, so it is reproducible for one lockfile; it
// records the lockfile's sha256 to bind the list to the dependency set.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  '..',
);
const OUTPUT = path.join(ROOT, 'THIRD_PARTY_NOTICES.md');
const COPYLEFT = /\b(A?GPL|LGPL|SSPL|EUPL|CPAL|OSL|BUSL)\b/i;

const read = (file) => fs.readFileSync(path.join(ROOT, file), 'utf8');
const exists = (file) => fs.existsSync(path.join(ROOT, file));

function packageName(key) {
  const marker = 'node_modules/';
  return key.slice(key.lastIndexOf(marker) + marker.length);
}

function undeclaredLicenceNote(key) {
  const dir = path.join(ROOT, key);
  if (!fs.existsSync(dir)) return 'no licence declared; package not installed here';
  const file = fs
    .readdirSync(dir)
    .find((name) => /^(licen[sc]e|copying)(\.|$)/i.test(name));
  if (!file) return 'no licence declared and no licence file found';
  const first = fs
    .readFileSync(path.join(dir, file), 'utf8')
    .split(/\r?\n/)
    .map((line) => line.trim())
    .find(Boolean);
  return `not declared in package.json; ${file} begins "${(first ?? '').slice(0, 60)}"`;
}

function collect() {
  const lock = JSON.parse(read('package-lock.json'));
  const rows = [];
  for (const [key, entry] of Object.entries(lock.packages ?? {})) {
    if (key === '' || entry.dev || entry.link) continue;
    rows.push({
      name: packageName(key),
      version: entry.version ?? '?',
      license:
        typeof entry.license === 'string' ? entry.license : undefined,
      note: entry.license ? undefined : undeclaredLicenceNote(key),
    });
  }
  rows.sort((a, b) =>
    a.name === b.name
      ? a.version < b.version
        ? -1
        : 1
      : a.name < b.name
        ? -1
        : 1,
  );
  const dev = Object.entries(lock.packages ?? {}).filter(
    ([key, entry]) => key !== '' && entry.dev,
  ).length;
  return { rows, devCount: dev, lock: read('package-lock.json') };
}

const cell = (text) => String(text).replaceAll('|', '\\|');

function render() {
  const { rows, devCount, lock } = collect();
  const lockHash = createHash('sha256').update(lock).digest('hex');
  const byLicense = new Map();
  for (const row of rows) {
    const label = row.license ?? 'NOT DECLARED';
    byLicense.set(label, (byLicense.get(label) ?? 0) + 1);
  }
  const summary = [...byLicense.entries()]
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .map(([license, count]) => `| ${cell(license)} | ${count} |`);
  const undeclared = rows.filter((row) => !row.license);
  const pkg = JSON.parse(read('package.json'));
  const out = [];
  out.push(
    '# Third-party notices',
    '',
    'NemoDots is an independent project built on OpenDots. This file is generated by `node scripts/nemodots/notices.mjs` from `LICENSE`, `deployment/computers/LICENSE.openbot` and `package-lock.json`; do not edit it by hand (`node scripts/nemodots/notices.mjs --check` fails when it is stale).',
    '',
    '## OpenDots (the base of this repository)',
    '',
    'This repository was created by importing CopilotKit/OpenDots at commit `ab39f2508f3fd23a949837622456f3d61a108e9a` (https://github.com/CopilotKit/OpenDots). Upstream code, tests, documentation and assets that NemoDots did not change remain under the upstream licence. The upstream notice, from `LICENSE`, is:',
    '',
    ...read('LICENSE')
      .trimEnd()
      .split(/\r?\n/)
      .map((line) => (line ? `> ${line}` : '>')),
    '',
    'NemoDots additions live under `src/server/nemodots/`, `src/client/nemodots/`, `tests/nemodots/`, `scripts/nemodots/` and `docs/nemodots/`, plus the small, optional-by-default edits to upstream server files described in `docs/nemodots/ARCHITECTURE.md`. Upstream attribution in `README.md` is kept.',
    '',
    '## OpenBot computer and supervisor service',
    '',
    exists('deployment/computers/LICENSE.openbot')
      ? 'The optional per-Dot computer feature uses the OpenBot computer service and supervisor (https://github.com/CopilotKit/OpenBot), built from the pinned commit `b6932d31a8d6e7896c15139dfc27a6c6911deb27` with the hardening script in `deployment/computers/`. NemoDots does not use it in the core demo. Its notice, from `deployment/computers/LICENSE.openbot`, is:'
      : 'deployment/computers/LICENSE.openbot is missing.',
    '',
    ...(exists('deployment/computers/LICENSE.openbot')
      ? read('deployment/computers/LICENSE.openbot')
          .trimEnd()
          .split(/\r?\n/)
          .map((line) => (line ? `> ${line}` : '>'))
      : []),
    '',
    '## Services NemoDots talks to (not distributed with it)',
    '',
    '| Service | Used for | Terms |',
    '| --- | --- | --- |',
    '| Crusoe Managed Inference (OpenAI-compatible Chat Completions) | Nemotron reasoning in the finished product | the account holder\'s Crusoe terms |',
    '| NVIDIA Nemotron models served by Crusoe | planning and worker reasoning | the model licence shown by the provider for the model used |',
    '| CopilotKit Intelligence | OpenDots conversations, threads and Learning | the account holder\'s CopilotKit terms; needs its own key |',
    '| PostgreSQL 16 and Redis 8 (installed by the operator) | the local sandbox stack | their own licences; not bundled |',
    '',
    '## npm packages',
    '',
    `Production (non-dev) packages recorded in \`package-lock.json\` (sha256 \`${lockHash}\`): **${rows.length}**. Dev-only packages (${devCount}) are build and test tools and are not distributed in the runtime.`,
    '',
    `Direct dependencies in \`package.json\`: ${Object.keys(pkg.dependencies ?? {}).length} production, ${Object.keys(pkg.devDependencies ?? {}).length} development.`,
    '',
    '### Licences in the production set',
    '',
    '| Licence (as declared) | Packages |',
    '| --- | --- |',
    ...summary,
    '',
  );
  if (undeclared.length) {
    out.push(
      '### Packages that declare no licence',
      '',
      ...undeclared.map(
        (row) => `- \`${row.name}@${row.version}\`: ${row.note}.`,
      ),
      '',
    );
  }
  out.push(
    '### All production packages',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...rows.map(
      (row) =>
        `| ${cell(row.name)} | ${cell(row.version)} | ${cell(row.license ?? 'NOT DECLARED')} |`,
    ),
    '',
  );
  const copyleft = rows.filter((row) => row.license && COPYLEFT.test(row.license));
  return { text: out.join('\n'), copyleft };
}

const args = new Set(process.argv.slice(2));
const { text, copyleft } = render();
if (args.has('--stdout')) {
  process.stdout.write(text);
} else if (args.has('--check')) {
  const current = fs.existsSync(OUTPUT) ? fs.readFileSync(OUTPUT, 'utf8') : null;
  if (copyleft.length) {
    console.error(
      `notices: copyleft licences in the production set: ${copyleft
        .map((row) => `${row.name}@${row.version} (${row.license})`)
        .join(', ')}`,
    );
    process.exit(1);
  }
  if (current !== text) {
    console.error(
      'notices: THIRD_PARTY_NOTICES.md is missing or stale; run node scripts/nemodots/notices.mjs',
    );
    process.exit(1);
  }
  console.log('notices: THIRD_PARTY_NOTICES.md is current');
} else {
  fs.writeFileSync(OUTPUT, text);
  console.log(`notices: wrote ${path.relative(ROOT, OUTPUT)}`);
}
